export function getMeritFlaw(id: string): MeritFlawEntry | undefined {
  return MERITS_FLAWS.find((entry) => entry.id === id);
}

export function getMeritFlawsByCategory(
  category: MeritFlawCategory,
  type: MeritFlawType,
): MeritFlawEntry[] {
  return MERITS_FLAWS.filter((entry) => entry.category === category && entry.type === type);
}
